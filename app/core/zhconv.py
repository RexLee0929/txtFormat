_FALLBACK_S2T: dict[str, str] = {}
for _s, _t in _FALLBACK_PAIRS:
    _FALLBACK_S2T.setdefault(_s, _t)
_FALLBACK_T2S: dict[str, str] = {}
for _s2, _t2 in _FALLBACK_PAIRS:
    _FALLBACK_T2S.setdefault(_t2, _s2)


def to_traditional(text: str) -> str:
    result = _native_map(text, LCMAP_TRADITIONAL_CHINESE)
    if result is not None:
        return result
    return "".join(_FALLBACK_S2T.get(ch, ch) for ch in text)


def to_simplified(text: str) -> str:
    result = _native_map(text, LCMAP_SIMPLIFIED_CHINESE)
    if result is not None:
        return result
    return "".join(_FALLBACK_T2S.get(ch, ch) for ch in text)


def traditional_chars(text: str) -> list[tuple[int, str, str]]:
    """找出文本中的繁体字，返回 [(位置, 原字, 简体字)]。"""
    mapping = to_simplified(text)
    if len(mapping) != len(text):
        mapping = "".join(_FALLBACK_T2S.get(ch, ch) for ch in text)
    out: list[tuple[int, str, str]] = []
    for i, (a, b) in enumerate(zip(text, mapping)):
        if a != b and "\u4e00" <= a <= "\u9fff":
            out.append((i, a, b))
    return out


CONVERT_MODES = [
    ("繁转简 (BIG5→GBK / 繁体→简体)", "t2s"),
    ("简转繁 (GBK→BIG5 / 简体→繁体)", "s2t"),
]


def convert(text: str, mode: str) -> str:
    if mode == "s2t":
        return to_traditional(text)
    if mode == "t2s":
        return to_simplified(text)
    return text


