"""简体 / 繁体转换。

优先调用 Windows 原生 ``LCMapStringEx``（与系统输入法、Office 使用同一套映射，
无需附带任何字表）；在非 Windows 或调用失败时退回内置常用字表。
"""

from __future__ import annotations

import ctypes
import sys

LCMAP_SIMPLIFIED_CHINESE = 0x02000000
LCMAP_TRADITIONAL_CHINESE = 0x04000000
LOCALE_NAME_SYSTEM_DEFAULT = "!x-sys-default-locale"


def _native_map(text: str, flag: int) -> str | None:
    if sys.platform != "win32":
        return None
    try:
        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        fn = kernel32.LCMapStringEx
        fn.argtypes = [ctypes.c_wchar_p, ctypes.c_uint32, ctypes.c_wchar_p,
                       ctypes.c_int, ctypes.c_wchar_p, ctypes.c_int,
                       ctypes.c_void_p, ctypes.c_void_p, ctypes.c_ssize_t]
        fn.restype = ctypes.c_int
        src = text
        size = fn(LOCALE_NAME_SYSTEM_DEFAULT, flag, src, len(src), None, 0, None, None, 0)
        if size <= 0:
            return None
        buf = ctypes.create_unicode_buffer(size + 1)
        got = fn(LOCALE_NAME_SYSTEM_DEFAULT, flag, src, len(src), buf, size + 1, None, None, 0)
        if got <= 0:
            return None
        return buf.value
    except (OSError, AttributeError):
        return None


